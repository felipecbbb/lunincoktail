export function pickTranslation<T extends { es: string; en?: string; uk?: string }>(
  obj: T,
  lang: Lang,
): string {
  if (lang === "uk" && obj.uk && obj.uk.length > 0) return obj.uk;
  if (lang === "en" && obj.en && obj.en.length > 0) return obj.en;
  return obj.es;
}
